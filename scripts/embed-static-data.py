"""Pre-build step for GitHub Pages static export.

Reads data/diy/*.json and data/news/*.json at build time and emits
src/generated/static-data.ts, which inlines the data as JS objects.
The static export then ships that bundle — the live site needs no
server or writable filesystem.

On a node deployment (npm run dev / npm start without Pages) this file
is not generated; DiyLib.ts / news lib fall back to live fs reads.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).parent.parent  # website/
DIY = ROOT / "data" / "diy"
NEWS = ROOT / "data" / "news"
OUT = ROOT / "src" / "generated" / "static-data.ts"


def read_all(dir: pathlib.Path):
    items = {}
    if not dir.is_dir():
        return items
    for f in sorted(dir.glob("*.json")):
        try:
            items[f.stem] = json.loads(f.read_text(encoding="utf-8"))
        except Exception as e:
            print(f"  warn: skip {f.name}: {e}")
    return items


diy = read_all(DIY)
news = sorted(read_all(NEWS).values(), key=lambda a: (a.get("date") or ""), reverse=True)

# slug -> index for getDiyPage()
slug_to_idx = {slug: i for i, slug in enumerate(sorted(diy.keys()))}

OUT.parent.mkdir(parents=True, exist_ok=True)
lines = []
lines.append("// AUTO-GENERATED by scripts/embed-static-data.py — do not edit by hand.")
lines.append("// Inlines data/diy + data/news so the GitHub Pages static export")
lines.append("// works without a node server. Regenerated on every build.")
lines.append("")
lines.append("export type DiyCard = { img: string; name: string; count?: string };")
lines.append("export type DiyPage = {")
lines.append("  slug: string;")
lines.append("  title: string;")
lines.append("  cover: string;")
lines.append("  cards: DiyCard[];")
lines.append("};")
lines.append("")
lines.append("export type NewsArticle = {")
lines.append("  slug: string;")
lines.append("  title: string;")
lines.append("  date: string;")
lines.append("  img: string;")
lines.append("  excerpt: string;")
lines.append("  body: string[];")
lines.append("};")
lines.append("")
lines.append(f"export const DIY_PAGES: DiyPage[] = {json.dumps(list(diy.values()), indent=1)};")
lines.append("")
lines.append(f"export const SLUG_INDEX: Record<string, number> = {json.dumps(slug_to_idx)};")
lines.append("")
lines.append(f"export const NEWS_ARTICLES: NewsArticle[] = {json.dumps(news, indent=1)};")
lines.append("")

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}  ({len(diy)} diy pages, {len(news)} news articles)")
